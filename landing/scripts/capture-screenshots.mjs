import { spawn, spawnSync } from "node:child_process";
import { mkdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "../..");
const outDir = resolve(__dirname, "../public/screenshots");
const frameWidth = 1440;
const frameHeight = 880;
const locales = ["ru", "en"];

function waitForUrl(url, timeoutMs = 60_000) {
  const start = Date.now();
  return new Promise((resolvePromise, reject) => {
    const tick = async () => {
      try {
        const res = await fetch(url);
        if (res.ok) {
          resolvePromise();
          return;
        }
      } catch {
        /* retry */
      }
      if (Date.now() - start > timeoutMs) {
        reject(new Error(`Timed out waiting for ${url}`));
        return;
      }
      setTimeout(tick, 400);
    };
    tick();
  });
}

function runVite() {
  const child = spawn(
    process.execPath,
    [
      resolve(root, "node_modules/vite/bin/vite.js"),
      "--host",
      "127.0.0.1",
      "--port",
      "4177",
      "--strictPort",
    ],
    {
      cwd: root,
      stdio: "inherit",
      env: { ...process.env, GSM_SCREENSHOT: "1" },
    },
  );
  return child;
}

async function main() {
  mkdirSync(outDir, { recursive: true });
  const vite = runVite();
  const baseUrl = "http://127.0.0.1:4177/screenshot.html";

  try {
    await waitForUrl(`${baseUrl}?lang=ru`);
    const browser = await chromium.launch();
    const page = await browser.newPage({
      viewport: { width: frameWidth, height: frameHeight },
      deviceScaleFactor: 2,
    });
    const errors = [];
    const dimensions = {};
    page.on("pageerror", (error) => errors.push(error.message));

    for (const locale of locales) {
      dimensions[locale] = {};
      const localeDir = resolve(outDir, locale);
      mkdirSync(localeDir, { recursive: true });
      for (const width of [740, 390]) {
        await page.setViewportSize({ width, height: 900 });
        for (const feature of ["preview", "restore", "diagnostics"]) {
          await page.goto(`${baseUrl}?lang=${locale}&feature=${feature}`, {
            waitUntil: "networkidle",
          });
          if (feature === "restore") {
            await page
              .getByRole("combobox", {
                name: locale === "ru" ? "Снимок" : "Snapshot",
                exact: true,
              })
              .selectOption("snapshot-demo");
            await page
              .getByText("r.Shadow.MaxResolution", { exact: false })
              .waitFor();
          }
          const frame = page.locator(
            feature === "preview" ? "#changes-preview" : "#shot-feature",
          );
          await frame.waitFor({ state: "visible" });
          await page.evaluate(() => document.fonts.ready);
          const filename = `${feature}${width === 390 ? "-mobile" : ""}`;
          const png = resolve(localeDir, `${filename}.png`);
          const webp = resolve(localeDir, `${filename}.webp`);
          await frame.screenshot({ path: png, type: "png" });
          const convert = spawnSync(
            "python",
            [
              "-c",
              "from PIL import Image; import sys,json; im=Image.open(sys.argv[1]); im.save(sys.argv[2], 'WEBP', lossless=True); print(json.dumps(im.size))",
              png,
              webp,
            ],
            { encoding: "utf8" },
          );
          if (convert.status !== 0)
            throw new Error(
              `WebP conversion requires Python/Pillow: ${convert.stderr}`,
            );
          dimensions[locale][filename] = JSON.parse(convert.stdout);
          unlinkSync(png);
          console.log(`saved ${locale}/${filename}.webp`);
        }
      }
      await page.setViewportSize({ width: frameWidth, height: frameHeight });
    }

    await browser.close();
    if (errors.length)
      throw new Error(`Screenshot frames failed: ${errors.join("; ")}`);
    writeFileSync(
      resolve(root, "landing/src/site/screenshots.ts"),
      `// Generated by landing/scripts/capture-screenshots.mjs.\nexport const screenshots = ${JSON.stringify(dimensions, null, 2)} as const;\n`,
    );
  } finally {
    if (process.platform === "win32")
      spawnSync("taskkill", ["/pid", String(vite.pid), "/T", "/F"], {
        stdio: "ignore",
      });
    else vite.kill("SIGTERM");
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
